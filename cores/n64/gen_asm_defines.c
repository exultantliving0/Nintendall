/**
 * Nintendall - asm_defines generator for the mupen64plus classic dynarec
 *
 * The nasm sources under device/r4300/x86_64/ need the byte offsets of a
 * handful of structure members that live in the emulator's C state.  Upstream
 * obtains them by compiling a crafted asm_defines.c, scraping the @ASM_DEFINE
 * strings out of the object file with a shell script and awk, and turning them
 * into asm_defines_nasm.h.
 *
 * Nintendall has no awk, so this program produces the same header directly
 * from offsetof() and is run once as a build step.  Usage:
 *
 *     gen_asm_defines <output-header>
 */

#include <stddef.h>
#include <stdio.h>

#include "device/device.h"
#include "device/r4300/r4300_core.h"

#define DEF(s, m) \
    fprintf(out, "%%define offsetof_struct_" #s "_" #m " (0x%llx)\n", \
            (unsigned long long)offsetof(struct s, m))

int main(int argc, char** argv)
{
    FILE* out;

    if (argc < 2) {
        fprintf(stderr, "usage: %s <output-header>\n", argv[0]);
        return 2;
    }

    out = fopen(argv[1], "wb");
    if (out == NULL) {
        fprintf(stderr, "gen_asm_defines: cannot open '%s'\n", argv[1]);
        return 1;
    }

    fprintf(out, "; Generated by Nintendall gen_asm_defines - do not edit\n");
    fprintf(out, "%%ifndef M64P_ASM_DEFINES_NASM_H\n");
    fprintf(out, "%%define M64P_ASM_DEFINES_NASM_H\n\n");

    DEF(device, r4300);

    /* The classic (non-new) dynarec keeps registers and cp0 state inline. */
    DEF(r4300_core, regs);
    DEF(r4300_core, hi);
    DEF(r4300_core, lo);
    DEF(r4300_core, stop);

    DEF(r4300_core, recomp);

#if defined(__x86_64__)
    DEF(recomp, save_rsp);
    DEF(recomp, save_rip);
#else
    DEF(recomp, save_ebp);
    DEF(recomp, save_esp);
    DEF(recomp, save_ebx);
    DEF(recomp, save_esi);
    DEF(recomp, save_edi);
    DEF(recomp, save_eip);
#endif
    DEF(recomp, return_address);

    DEF(r4300_core, cp0);
    DEF(cp0, regs);
    DEF(cp0, next_interrupt);
    DEF(cp0, last_addr);
    DEF(cp0, count_per_op);
    DEF(cp0, tlb);

    DEF(tlb, entries);
    DEF(tlb, LUT_r);
    DEF(tlb, LUT_w);

    DEF(r4300_core, cached_interp);
    DEF(cached_interp, invalid_code);

    fprintf(out, "\n%%endif\n");
    fclose(out);
    return 0;
}
